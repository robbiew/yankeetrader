def flags_for(c):
    raw=bytes.fromhex(c['left']) if c['op'] in(167,168) else bytes.fromhex(c['fac'])
    top=raw[2] if c['op']==167 else raw[6];exp=raw[3] if c['op']==167 else raw[7]
    f=(4 if exp.bit_count()%2==0 else 0)|(64 if exp==0 else 0)|(128 if exp&128 else 0)
    if exp:f|=(top>>7)|(2048 if ((top>>6)^(top>>7))&1 else 0)
    return f

def branches_for(flags):
    c,p,z,s,o=(bool(flags&bit)for bit in (1,4,64,128,2048))
    return bytes(map(int,(o,not o,c,not c,z,not z,c or z,not c and not z,s,not s,p,not p,s!=o,s==o,z or s!=o,not z and s==o)))

