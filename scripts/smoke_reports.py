"""Exercise remote report privacy and persisted turn charges with real GoDoors PTYs."""
from pathlib import Path
import datetime
import errno
import json
import os
import pty
import re
import select
import subprocess
import tempfile
import time

ROOT = Path(__file__).resolve().parents[1]
BINARY = str(ROOT / "bin/yt")


def play(data, alias, commands, classic=False):
    master, slave = pty.openpty()
    options = ["-ascii"] if classic else ["-compact"]
    proc = subprocess.Popen([BINARY, *options, "-data", str(data), "-local", alias],
                            stdin=slave, stdout=slave, stderr=slave)
    os.close(slave)
    steps = [(b"[ Press any Key ]", b" ")] * 3 if classic else []
    steps += [(b"Main Command (?=Help)?" if classic else b"> ", commands.encode() + b"\r")]
    output = pending = b""
    step = 0
    deadline = time.monotonic() + 20
    try:
        while time.monotonic() < deadline:
            if not select.select([master], [], [], .1)[0]:
                continue
            try:
                chunk = os.read(master, 65536)
            except OSError as err:
                if err.errno == errno.EIO:
                    break
                raise
            if not chunk:
                break
            output += chunk
            pending += chunk
            if step < len(steps) and steps[step][0] in pending:
                marker, answer = steps[step]
                pending = pending.split(marker, 1)[1]
                os.write(master, answer)
                step += 1
        proc.wait(timeout=2)
        text = output.decode(errors="replace").replace("\r", "")
        assert proc.returncode == 0 and step == len(steps), text
        return text
    finally:
        if proc.poll() is None:
            proc.kill()
            proc.wait()
        os.close(master)


with tempfile.TemporaryDirectory(prefix="yt-reports-smoke-") as temp:
    data = Path(temp) / "world"
    subprocess.run([BINARY, "-data", str(data), "-init", "-sectors", "8"], check=True, capture_output=True)
    play(data, "Caller", "q")
    play(data, "Owner", "q")
    path = data / "world.json"
    world = json.loads(path.read_text())
    world["Ports"]["2"]["Name"] = "Trading Post"
    stamp = datetime.datetime.now(datetime.timezone.utc).isoformat()
    for planet_id, sector, owner, name, bank in [(2, 3, 2, "Private World", 9876543), (3, 4, 1, "Home", 34567)]:
        world["Sectors"][str(sector)]["Planet"] = planet_id
        world["Planets"][str(planet_id)] = dict(ID=planet_id, Sector=sector, Owner=owner,
            Name=name, Bank=bank, Ground=12, Updated=stamp, Production=[1, 2, 3], Cargo=[4, 5, 6])
    path.write_text(json.dumps(world))
    # Normalize hand-written fixture fields through Go's save encoder before
    # comparing economic state, including zero fields and UTC timestamps.
    play(data, "Caller", "q")
    world = json.loads(path.read_text())

    text = play(data, "Caller", "c;2;2;9;3;13;1;q;y", classic=True)
    transcript = text
    assert "Commerce report for Trading Post" in text and "Planet: Home" in text, text
    assert "Planet: Private World -*- Ground Forces: 12" in text, text
    assert "9876543" not in text and "Credits......" not in text, text
    saved = json.loads(path.read_text())
    assert saved["Players"]["1"]["Turns"] == 500 and saved["Players"]["1"]["Sector"] == 1
    assert saved["Planets"] == world["Planets"] and saved["Ports"] == world["Ports"]

    text = play(data, "Caller", "planetreport 4;q")
    transcript += text
    bank = re.search(r"Credits\.{6}\s+\d+\s+(\d+)\s+", text)
    assert bank and int(bank[1]) >= 34567 and "Private World" not in text, text
    world = json.loads(path.read_text())
    world["Planets"]["2"]["Ground"] = 0
    world["Planets"]["2"]["Bank"] = 0
    path.write_text(json.dumps(world))
    text = play(data, "Caller", "planetreport 3;q")
    transcript += text
    bank = re.search(r"Credits\.{6}\s+\d+\s+(\d+)\s+", text)
    assert bank and int(bank[1]) == 0, text

    # Stored zero ground does not grant access when bank-funded ground has
    # regenerated by report time. Projected defenses must protect the bank.
    world = json.loads(path.read_text())
    world["Planets"]["2"]["Bank"] = 9876543
    world["Planets"]["2"]["Updated"] = (datetime.datetime.now(datetime.timezone.utc) - datetime.timedelta(days=1)).isoformat()
    path.write_text(json.dumps(world))
    text = play(data, "Caller", "planetreport 3;q")
    transcript += text
    assert "Planet: Private World -*- Ground Forces:" in text and "Credits......" not in text, text
    saved = json.loads(path.read_text())
    assert saved["Planets"]["2"]["Bank"] == 9876543 and saved["Planets"]["2"]["Ground"] == 0

    world = json.loads(path.read_text())
    for sector in (2, 3):
        world["Sectors"][str(sector)]["Defense"] = dict(Owner=2, Fighters=50)
    path.write_text(json.dumps(world))
    text = play(data, "Caller", "portreport 2;planetreport 3;q")
    transcript += text
    assert text.count("No information available.") == 2 and "One turn spent" in text, text
    assert "Trading Post" not in text and "Private World" not in text and "9876543" not in text, text
    world = json.loads(path.read_text())
    assert world["Players"]["1"]["Turns"] == 499 and world["Players"]["1"]["Sector"] == 1
    assert world["Planets"]["2"]["Bank"] == 9876543
    text = play(data, "Caller", "myplanets;i;q")
    transcript += text
    assert "499 turns >" in text and "Planet: Home" in text and "Private World" not in text, text
    assert json.loads(path.read_text())["Players"]["1"]["Turns"] == 499
    (ROOT / "evidence/reports-smoke.txt").write_text(transcript)
    print("Reports PTY passed: classic computer options 2/9/13, private/full planet detail, blocked port/planet reports, persisted single-turn charge and reconnect.")
