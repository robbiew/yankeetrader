def expected_payload(c):
    assert c['op'] in (0x9f,0xa1,0xa3) and c['seed_flags'] in (0,0x8d5)
    def assign(at,raw):return b''.join(bytes.fromhex('c706')+struct.pack('<HH',at+2*i,w)for i,w in enumerate(struct.unpack('<'+'H'*(len(raw)//2),raw)))
    def word(at,v):return assign(at,struct.pack('<H',v))
    def output(at,n):return bytes.fromhex('bb0100b9')+struct.pack('<H',n)+b'\xba'+struct.pack('<H',at)+bytes.fromhex('b440cd21')
    setup=bytes.fromhex('fc1e07')+assign(0x16,bytes.fromhex(c['fac']))+assign(0x1860,bytes.fromhex(c['left']))+assign(0x1864,bytes.fromhex(c['right']))
    setup+=assign(0x1856,b'SCF1')+word(0x1870,c['op'])+word(0x1872,c['seed_flags'])+bytes.fromhex('8c1e74188c067618892e7818')
    prefix=b''.join(output(at,n)for at,n in ((0x1856,4),(0x234,4),(0x16,8),(0x1860,4),(0x1864,4),(0x1f,1),(0x1870,1),(0x1872,8)))
    call=bytes.fromhex('be6018bf6418fc9c58252af70d')+struct.pack('<H',c['seed_flags'])+bytes.fromhex('509d9c8f06b018b8efbebb0bb0b9fecabad0d0')+bytes([0xcd,0x3f,c['op'],0x90,0x90])+bytes.fromhex('9c8f06b218')
    branches=b''.join(bytes.fromhex('c606')+struct.pack('<H',0x18c0+i)+b'\x00'+bytes([0x70+(i^1),5])+bytes.fromhex('c606')+struct.pack('<H',0x18c0+i)+b'\x01'for i in range(16))
    saved=bytes.fromhex('a3f018891ef218890ef4188916f6188936f818893efa18892efc188c1efe188c060019')
