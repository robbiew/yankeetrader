def flags_for(left,right):
    # Source model: logical byte flags plus one-bit RCL, or descending CMPSW.
    def logical(v):return (4 if v.bit_count()%2==0 else 0)|(64 if v==0 else 0)|(128 if v&128 else 0)
    def rotate(v,f):return (f&~0x801)|((v>>7)&1)|(0x800 if ((v>>6)^(v>>7))&1 else 0)
    if not right[3]:
        f=logical(left[3]);return rotate(left[2],f)if left[3]else f
    if not left[3]:return rotate(right[2],logical(right[3]))^1
    f=rotate(left[2],logical(left[2]^right[2]))
    if f&128:return f
    if left[2]&128:left,right=right,left
    high_left,high_right=int.from_bytes(left[2:],'little'),int.from_bytes(right[2:],'little')
    x,y=(high_left,high_right)if high_left!=high_right else (int.from_bytes(left[:2],'little'),int.from_bytes(right[:2],'little'))
    diff=(x-y)&65535
    return (1 if x<y else 0)|(4 if (diff&255).bit_count()%2==0 else 0)|(64 if diff==0 else 0)|(128 if diff&32768 else 0)|(0x800 if (x^y)&(x^diff)&32768 else 0)

def branches_for(flags):
    c,p,z,s,o=(bool(flags&bit)for bit in (1,4,64,128,2048))
    return bytes(map(int,(o,not o,c,not c,z,not z,c or z,not c and not z,s,not s,p,not p,s!=o,s==o,z or s!=o,not z and s==o)))

