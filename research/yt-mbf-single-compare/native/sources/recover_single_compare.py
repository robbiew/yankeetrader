def payload(c):
    assert c['op'] in (0x9f,0xa1,0xa3) and c['seed_flags'] in (0,0x8d5)
    b=bytearray()
    def emit(s):b.extend(bytes.fromhex(s))
    def assign(at,raw):
        for i in range(0,len(raw),2):b.extend(bytes.fromhex('c706')+struct.pack('<HH',at+i,int.from_bytes(raw[i:i+2],'little')))
    def word(at,v):assign(at,struct.pack('<H',v))
    def output(at,n):b.extend(bytes.fromhex('bb0100b9')+struct.pack('<H',n)+b'\xba'+struct.pack('<H',at)+bytes.fromhex('b440cd21'))
    emit('fc1e07');assign(0x16,bytes.fromhex(c['fac']));assign(0x1860,bytes.fromhex(c['left']));assign(0x1864,bytes.fromhex(c['right']))
    assign(0x1856,b'SCF1');word(0x1870,c['op']);word(0x1872,c['seed_flags']);emit('8c1e74188c067618892e7818')
    for at,n in ((0x1856,4),(0x234,4),(0x16,8),(0x1860,4),(0x1864,4),(0x1f,1),(0x1870,1),(0x1872,8)):output(at,n)
    emit('be6018bf6418fc9c58252af70d');b.extend(struct.pack('<H',c['seed_flags']));emit('509d9c8f06b018b8efbebb0bb0b9fecabad0d0')
    b.extend(bytes([0xcd,0x3f,c['op'],0x90,0x90]));emit('9c8f06b218')
    # MOVs and conditional jumps preserve the flags: all sixteen Jcc conditions
    # see the immediate comparison result, without reloading or synthesizing it.
    for i in range(16):
        b.extend(bytes.fromhex('c606')+struct.pack('<H',0x18c0+i)+b'\x00'+bytes([0x70+(i^1),5])+bytes.fromhex('c606')+struct.pack('<H',0x18c0+i)+b'\x01')
    emit('a3f018891ef218890ef4188916f6188936f818893efa18892efc188c1efe188c060019')
    for at,n in ((0x18b0,4),(0x18c0,16),(0x18f0,18),(0x16,8),(0x1860,4),(0x1864,4),(0x234,4),(0x1f,1)):output(at,n)
    assign(0x1856,b'END!');output(0x1856,4);emit('b8004ccd21');return bytes(b)

